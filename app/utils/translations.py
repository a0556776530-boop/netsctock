def localize_form(form, t, submit_key=None, extra=None):
    """Apply translated labels to a WTForms form instance."""
    for field_name, t_key in _FIELD_KEY_MAP.items():
        field = getattr(form, field_name, None)
        if field is not None and t_key in t:
            field.label.text = t[t_key]
    if extra:
        for field_name, t_key in extra.items():
            field = getattr(form, field_name, None)
            if field is not None and t_key in t:
                field.label.text = t[t_key]
    if submit_key and submit_key in t and hasattr(form, 'submit'):
        form.submit.label.text = t[submit_key]
    return form


def _t(key, **kwargs):
    """Get a translated string for the current request's language."""
    from flask import g
    t = getattr(g, 't', None) or TRANSLATIONS['en']
    text = t.get(key, TRANSLATIONS['en'].get(key, key))
    return text.format(**kwargs) if kwargs else text
